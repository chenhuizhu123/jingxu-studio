              throw ArgumentError('unsupportedAction');
          }
        },
      );
      return mutate(
        id,
        (p) => (p['messages'] as List).add({
          'id': newId(),
          'role': 'assistant',
          'text': answer,
          'createdAt': timestamp(),
          'skill': skill,
        }),
      );
    } finally {
      _agentBusy.remove(id);
    }
  }

